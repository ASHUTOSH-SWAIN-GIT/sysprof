//go:build ignore

// gensyscalls turns the kernel syscall tables into Go lookup tables.
//
//	go run tools/gensyscalls/main.go <syscall_64.tbl> <asm-generic/unistd.h>
//
// x86_64 numbers come from arch/x86/entry/syscalls/syscall_64.tbl,
// arm64 numbers from include/uapi/asm-generic/unistd.h.
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gensyscalls <syscall_64.tbl> <unistd.h>")
		os.Exit(1)
	}
	write("internal/syscalls/table_amd64.go", "amd64", parseX86(os.Args[1]))
	write("internal/syscalls/table_arm64.go", "arm64", parseGeneric(os.Args[2]))
}

func lines(path string) []string {
	f, err := os.Open(path)
	if err != nil {
		panic(err)
	}
	defer f.Close()
	var out []string
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		out = append(out, sc.Text())
	}
	return out
}

func parseX86(path string) map[int]string {
	m := map[int]string{}
	for _, l := range lines(path) {
		if strings.HasPrefix(l, "#") {
			continue
		}
		f := strings.Fields(l)
		if len(f) < 3 || f[1] == "x32" {
			continue
		}
		n, err := strconv.Atoi(f[0])
		if err != nil {
			continue
		}
		m[n] = f[2]
	}
	return m
}

var nrRe = regexp.MustCompile(`^#define\s+__NR(?:3264)?_(\w+)\s+(\d+)\s*$`)

func parseGeneric(path string) map[int]string {
	m := map[int]string{}
	for _, l := range lines(path) {
		g := nrRe.FindStringSubmatch(l)
		if g == nil || g[1] == "syscalls" {
			continue
		}
		n, _ := strconv.Atoi(g[2])
		if n >= 1024 { // deprecated aliases (open, stat, ...) are not real arm64 syscalls
			continue
		}
		m[n] = g[1]
	}
	return m
}

func write(path, arch string, m map[int]string) {
	keys := make([]int, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Ints(keys)
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/gensyscalls; DO NOT EDIT.\n\n//go:build %s\n\npackage syscalls\n\nvar names = map[int]string{\n", arch)
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%d: %q,\n", k, m[k])
	}
	b.WriteString("}\n")
	src, err := format.Source([]byte(b.String()))
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile(path, src, 0o644); err != nil {
		panic(err)
	}
}
